    END IF;
END $$;

-- =============================================
-- TRAINING COST LOG ITEMS TABLE (Enhanced Traceability)
-- =============================================
CREATE TABLE IF NOT EXISTS training_cost_log_items (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    training_cost_log_id UUID REFERENCES training_cost_logs(id) ON DELETE CASCADE NOT NULL,
    
    -- Item identification
    item_name VARCHAR(255) NOT NULL,
    item_type VARCHAR(50) NOT NULL, -- 'consumable' | 'reagent' | 'standard' | 'barang'
    
    -- Traceability: link to source batch
    catalog_id UUID,            -- FK to catalog (reagent_catalog, standard_catalog, items_catalog)
    warehouse_item_id UUID,     -- FK to warehouse_items (for consumable/barang)
    warehouse_chemical_id UUID, -- FK to warehouse_chemicals (for reagent/standard)
    
    -- Quantity & Cost snapshot (immutable at execution time)
    quantity DECIMAL(10,2) NOT NULL,
    unit VARCHAR(50),
    unit_cost DECIMAL(15,4) NOT NULL, -- Snapshot harga per unit saat eksekusi
    total_cost DECIMAL(15,2) NOT NULL,
    
    created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW() NOT NULL
);

COMMENT ON TABLE training_cost_log_items IS 'Detail item per eksekusi training dengan biaya dan traceability';
COMMENT ON COLUMN training_cost_log_items.catalog_id IS 'Reference to source catalog for audit trail';
COMMENT ON COLUMN training_cost_log_items.warehouse_item_id IS 'Reference to specific warehouse_items batch used';
COMMENT ON COLUMN training_cost_log_items.warehouse_chemical_id IS 'Reference to specific warehouse_chemicals batch used';
COMMENT ON COLUMN training_cost_log_items.unit_cost IS 'Price snapshot at execution time - immutable';

