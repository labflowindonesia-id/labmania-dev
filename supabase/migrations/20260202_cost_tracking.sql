-- =============================================
-- TRAINING COST LOGS TABLE
-- =============================================
CREATE TABLE IF NOT EXISTS training_cost_logs (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    training_set_id UUID REFERENCES training_sets(id) ON DELETE SET NULL,
    training_name VARCHAR(255) NOT NULL,
    executed_at TIMESTAMP WITH TIME ZONE DEFAULT NOW() NOT NULL,
    executed_by UUID REFERENCES profiles(id) ON DELETE SET NULL,
    executed_by_name VARCHAR(100),
    participants INTEGER NOT NULL,
    sets_used INTEGER NOT NULL DEFAULT 1,
    total_cost DECIMAL(15,2) NOT NULL DEFAULT 0,
    idempotency_key VARCHAR(64) UNIQUE, -- Hash untuk cegah double execution
    notes TEXT,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW() NOT NULL
);

-- Unique constraint on idempotency_key (primary guard for duplicates)
-- The idempotency_key is a SHA256 hash generated by the application
-- No functional index needed - we just ensure idempotency_key is UNIQUE (already defined in table)

COMMENT ON TABLE training_cost_logs IS 'Log eksekusi training dengan total biaya';
COMMENT ON COLUMN training_cost_logs.idempotency_key IS 'SHA256 hash dari training_set_id + participants + user + timestamp_minute untuk cegah duplicate';

-- Enable RLS
ALTER TABLE training_cost_logs ENABLE ROW LEVEL SECURITY;

-- RLS Policies for training_cost_logs
